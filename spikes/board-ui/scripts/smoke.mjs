import { chromium } from "@playwright/test"
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.on("console", (m) => console.log("console:", m.type(), m.text()))
page.on("pageerror", (e) => console.log("pageerror:", e.message))
await page.goto("http://localhost:5199/")
await page.waitForSelector("[data-card-id]")
console.log("cards", await page.locator("[data-card-id]").count())
await page.screenshot({ path: process.argv[2] ?? "smoke.png" })
await page.evaluate(() => window.__cello.scenarios.single())
await page.waitForTimeout(500)
await page.screenshot({ path: (process.argv[2] ?? "smoke.png").replace(".png", "-mid.png") })
await page.waitForTimeout(1500)
console.log(await page.evaluate(() => JSON.stringify({ s: window.__cello.stats, ghosts: window.__cello.activeGhosts(), anims: document.getAnimations().length })))
await browser.close()
