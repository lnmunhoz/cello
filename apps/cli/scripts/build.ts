// Builds the `cello` binary: builds the web app, then compiles the CLI with every file of
// apps/web/dist embedded (Bun's `with { type: "file" }` imports), so `cello start` serves the board
// with nothing next to the binary, and the commit it's built from (CELLO_BUILD_COMMIT, else HEAD)
// embedded as its build (CEL-37), with the checkout it was built in, for the build history to read the
// commits between builds from (CEL-50). Output: apps/cli/dist/cello.
import * as fs from "node:fs"
import * as path from "node:path"
import { buildCommit } from "../../server/src/build/git.ts"

const cli = path.join(import.meta.dir, "..")
const web = path.join(cli, "../web")
const dist = path.join(web, "dist")
const run = (cmd: string[], cwd: string) => {
  const result = Bun.spawnSync(cmd, { cwd, stdout: "inherit", stderr: "inherit" })
  if (result.exitCode !== 0) process.exit(result.exitCode ?? 1)
}

if (!process.argv.includes("--skip-web")) run(["bun", "run", "build"], web)

const files: string[] = []
const walk = (dir: string) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else if (entry.isFile()) files.push(path.relative(dist, full).split(path.sep).join("/"))
  }
}
walk(dist)
if (!files.includes("index.html")) throw new Error(`No web build in ${dist}`)

const buildDir = path.join(cli, ".build")
fs.mkdirSync(buildDir, { recursive: true })
const entry = [
  "// Generated by scripts/build.ts: the CLI with the web app embedded.",
  'import { main } from "../src/main.ts"',
  ...files.map((file, i) => `import f${i} from ${JSON.stringify(`../../web/dist/${file}`)} with { type: "file" }`),
  "const files = new Map<string, string>([",
  ...files.map((file, i) => `  [${JSON.stringify(`/${file}`)}, f${i}],`),
  "])",
  `main(() => files, { commit: ${JSON.stringify(buildCommit(process.env, cli))}, checkout: ${JSON.stringify(cli)} })`,
  "",
].join("\n")
fs.writeFileSync(path.join(buildDir, "entry.ts"), entry)

const outfile = path.join(cli, "dist", "cello")
run(["bun", "build", "--compile", path.join(buildDir, "entry.ts"), "--outfile", outfile], cli)
console.log(`Built ${outfile} (${(fs.statSync(outfile).size / 1024 / 1024).toFixed(1)} MB, ${files.length} web files embedded)`)
